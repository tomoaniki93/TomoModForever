local function Paint(t, c, a) t:SetVertexColor(c[1], c[2], c[3], a or 1) end

local function Shown(region, on) if on then region:Show() else region:Hide() end end

-- An icon of the Codex folder inside a text, tinted (r, g, b from 0 to 255).
local function Glyph(file, size, r, g, b)
    return string.format("|T%s%s.tga:%d:%d:0:0:32:32:0:32:0:32:%d:%d:%d|t", TEX, file, size, size, r, g, b)
end
local ARROW_GLYPH = Glyph("arrow", 10, 201, 162, 82)
local NEW_GLYPH   = Glyph("diamond", 8, 255, 209, 0)

-- Poppins has no arrow glyph: the routes get a drawn one, not an empty box.
local function Pretty(text)
    if type(text) ~= "string" then return text end
    return (text:gsub("→", ARROW_GLYPH))
end

-- Tweens. One hidden frame drives them all and goes back to sleep when none
-- is left. key: what is animated; a new tween on a key replaces the old one.
local tweens = {}
local driver = CreateFrame("Frame")
driver:Hide()
driver:SetScript("OnUpdate", function(self, elapsed)
    if elapsed > 0.05 then elapsed = 0.05 end
    local busy = false
    for key, tw in pairs(tweens) do
        tw.t = tw.t + elapsed
        if tw.t >= tw.d then
            tweens[key] = nil
            tw.fn(tw.to)
        else
            busy = true
            if tw.t > 0 then
                local left = 1 - tw.t / tw.d
                tw.fn(tw.to + (tw.from - tw.to) * left * left * left)   -- ease out
            end
        end
    end
    if not busy then self:Hide() end
end)

local function Tween(key, from, to, duration, fn, delay)
    if from == to or duration <= 0 then
        tweens[key] = nil
        fn(to)
        return
    end
    tweens[key] = { t = -(delay or 0), d = duration, from = from, to = to, fn = fn }
    fn(from)
    driver:Show()
end

local function Fade(region, alpha, duration, delay)
    Tween(region, region:GetAlpha(), alpha, duration, function(v) region:SetAlpha(v) end, delay)
end

-- The rows of a list arrive one after the other.
local function Cascade(list, count)
    for i = 1, count do
        local r = list[i]
        if r:IsShown() then
            r:SetAlpha(0)
            Fade(r, 1, 0.20, (i - 1) * 0.016)
        end
    end
end

