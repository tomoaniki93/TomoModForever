    under:SetPoint("BOTTOMLEFT", 0, -1); under:SetPoint("BOTTOMRIGHT", 0, -1)

    -- Above everything (it takes no clicks): the gold rule and the corners.
    local deco = CreateFrame("Frame", nil, f)
    deco:SetAllPoints()
    deco:SetFrameLevel(f:GetFrameLevel() + 30)
    local rule = Tex(deco, "ARTWORK", "fade_c")
    rule:SetHeight(1); rule:SetPoint("TOP", 0, -BAR_H); rule:SetWidth(f:GetWidth() - 2)
    Paint(rule, YELLOW, 0.95)
    for _, k in ipairs({ { "TOPLEFT", 0, 1, 0, 1 }, { "TOPRIGHT", 1, 0, 0, 1 },
                         { "BOTTOMLEFT", 0, 1, 1, 0 }, { "BOTTOMRIGHT", 1, 0, 1, 0 } }) do
        local o = Tex(deco, "OVERLAY", "corner")
        o:SetSize(16, 16)
        o:SetPoint(k[1])
        o:SetTexCoord(k[2], k[3], k[4], k[5])
        Paint(o, GOLD)
    end

    f:SetScript("OnShow", function(self)
        self:SetAlpha(0)
        Fade(self, 1, 0.22)
        local full = self:GetWidth() - 2
        Tween(rule, 0.3, 1, 0.50, function(p) rule:SetWidth(full * p) end)
    end)
    return bar
end

