-- Text: a soft drop shadow rather than an outline, which stays crisp on the
-- dark panel.
local function FS(parent, font, size, color, justify)
    local f = parent:CreateFontString(nil, "OVERLAY")
    f:SetFont(font, size, "")
    f:SetShadowColor(0, 0, 0, 0.85)
    f:SetShadowOffset(1, -1)
    f:SetTextColor(color[1], color[2], color[3])
    f:SetJustifyH(justify or "LEFT")
    return f
end

-- A hairline. file: nil plain, "fade_h" fading to the right, "fade_c" fading
-- at both ends.
local function Rule(parent, file, color, alpha, layer)
    local t = Tex(parent, layer or "ARTWORK", file)
    Paint(t, color or BRONZE, alpha or 0.7)
    t:SetHeight(1)
    return t
end

-- A one-pixel box around `around` (the parent by default); returns its lines.
local function Border(parent, color, alpha, layer, around)
    around = around or parent
    local lines = {}
    for _, side in ipairs({ "TOP", "BOTTOM", "LEFT", "RIGHT" }) do
        local t = Tex(parent, layer or "BORDER")
        Paint(t, color, alpha)
        if side == "TOP" or side == "BOTTOM" then
            t:SetPoint(side .. "LEFT", around, side .. "LEFT", 0, 0)
            t:SetPoint(side .. "RIGHT", around, side .. "RIGHT", 0, 0)
            t:SetHeight(1)
        else
            t:SetPoint("TOP" .. side, around, "TOP" .. side, 0, 0)
            t:SetPoint("BOTTOM" .. side, around, "BOTTOM" .. side, 0, 0)
            t:SetWidth(1)
        end
        lines[#lines + 1] = t
    end
    return lines
end

-- A button. kind: nil (dark, bronze edge), "primary" (gold, the main action)
-- or "ghost" (no box until hovered). icon: a Codex texture left of the label,
-- or on the right edge with iconRight. .text and SetEnabled stay what the
-- rest of the file expects.
local function Flat(parent, w, h, label, onClick, kind, icon, iconRight)
    local b = CreateFrame("Button", nil, parent)
    b:SetSize(w, h)
    local primary, ghost = kind == "primary", kind == "ghost"

    local bg = Tex(b, "BACKGROUND")
    bg:SetAllPoints()
    if primary then Paint(bg, BRONZE) else bg:SetVertexColor(0.115, 0.092, 0.068, ghost and 0 or 1) end
    b.bg = bg
    local sheen = Tex(b, "BACKGROUND", "fade_v", 1)             -- light from above
    sheen:SetAllPoints()
    Paint(sheen, primary and YELLOW or GOLD, primary and 0.60 or (ghost and 0 or 0.10))
    local edge = Border(b, primary and YELLOW or BRONZE, ghost and 0 or 0.85)
    local glow = Tex(b, "ARTWORK", nil, -1)                      -- hover
    glow:SetAllPoints()
    Paint(glow, primary and TEXT or GOLD)
    glow:SetAlpha(0)

    local fs = FS(b, FONT_BOLD, 11, primary and INK or TEXT, "CENTER")
    if primary then fs:SetShadowColor(1, 0.92, 0.65, 0.35) end
    fs:SetText(label)
    b.text = fs
    if icon then
        local ic = Tex(b, "OVERLAY", icon)
        ic:SetSize(12, 12)
        Paint(ic, primary and INK or GOLD)
        b.icon = ic
        if label == "" then
            ic:SetPoint("CENTER")
        elseif iconRight then
            ic:SetPoint("RIGHT", -7, 0)
            fs:SetPoint("CENTER", -6, 0)
        else
            ic:SetPoint("RIGHT", fs, "LEFT", -5, 0)
            fs:SetPoint("CENTER", 8, 0)
        end
    else
        fs:SetPoint("CENTER")
    end

    function b:Hover(on)
        Fade(glow, on and (primary and 0.25 or 0.16) or 0, on and 0.10 or 0.25)
        if not primary and not ghost then
            for _, t in ipairs(edge) do Paint(t, on and GOLD or BRONZE, on and 1 or 0.85) end
        end
    end
    b:SetScript("OnEnter", function(self) if self:IsEnabled() then self:Hover(true) end end)
    b:SetScript("OnLeave", function(self) self:Hover(false) end)
    b:SetScript("OnMouseDown", function(self) if self:IsEnabled() then Fade(glow, primary and 0.05 or 0.30, 0.05) end end)
    b:SetScript("OnMouseUp", function(self) self:Hover(self:IsEnabled() and self:IsMouseOver()) end)
    b:SetScript("OnClick", onClick)
    hooksecurefunc(b, "SetEnabled", function(self, on)
        self:SetAlpha(on and 1 or 0.40)
        if not on then self:Hover(false) end
    end)
    return b
end

-- A row of text tabs sharing one gold underline, which slides to the active
-- tab. Add returns the tab (a button with .text); Select marks one active.
local function TabStrip(parent, h)
    local s = CreateFrame("Frame", nil, parent)
    s:SetHeight(h)
    s.tabs, s.used = {}, 0
    local base = Rule(s, nil, BRONZE, 0.45, "BACKGROUND")
    base:SetPoint("BOTTOMLEFT"); base:SetPoint("BOTTOMRIGHT")
    local mark = Tex(s, "ARTWORK")
    mark:SetHeight(2); mark:SetWidth(1)
    mark:SetPoint("BOTTOMLEFT", 0, 0)
    Paint(mark, YELLOW)
    local halo = Tex(s, "BACKGROUND", "fade_v", 1)               -- soft light above the underline
    halo:SetTexCoord(0, 1, 1, 0)
    halo:SetPoint("BOTTOMLEFT", mark, "TOPLEFT", 0, 0)
    halo:SetPoint("BOTTOMRIGHT", mark, "TOPRIGHT", 0, 0)
    halo:SetHeight(h - 6)
    Paint(halo, GOLD, 0.22)

    local function Place(x, w)
        s.markX, s.markW = x, w
        mark:SetPoint("BOTTOMLEFT", x, 0)
        mark:SetWidth(w)
    end

    function s:Add(w, label, onClick)
        local b = CreateFrame("Button", nil, s)
        b:SetSize(w, h)
        b:SetPoint("LEFT", s.used, 0)
        b.x = s.used
        s.used = s.used + w
        s:SetWidth(s.used)
        b.text = FS(b, FONT_BOLD, 11, DIM, "CENTER")
        b.text:SetPoint("CENTER", 0, 1)
        b.text:SetText(label)
        b:SetScript("OnEnter", function(self) if not self.on then self.text:SetTextColor(TEXT[1], TEXT[2], TEXT[3]) end end)
        b:SetScript("OnLeave", function(self) if not self.on then self.text:SetTextColor(DIM[1], DIM[2], DIM[3]) end end)
        b:SetScript("OnClick", onClick)
        s.tabs[#s.tabs + 1] = b
        return b
    end

    function s:Select(tab)
        for _, b in ipairs(s.tabs) do
            b.on = b == tab
            local c = b.on and YELLOW or DIM
            b.text:SetTextColor(c[1], c[2], c[3])
        end
        local x1, w1 = tab.x + 6, tab:GetWidth() - 12
        if not s.markX or not s:IsVisible() then Place(x1, w1) return end
        local x0, w0 = s.markX, s.markW
        Tween(s, 0, 1, 0.20, function(p) Place(x0 + (x1 - x0) * p, w0 + (w1 - w0) * p) end)
    end
    return s
end

-- Hover and selection of a list row: a gold wash fading to the right and,
-- when selected, a bright bar on the left edge. plain: hover only.
local function RowLook(r, plain)
    r.hl = Tex(r, "BACKGROUND", "fade_h")
    r.hl:SetAllPoints(); Paint(r.hl, GOLD); r.hl:SetAlpha(0)
    function r:SetHover(on) Fade(self.hl, on and 0.20 or 0, on and 0.08 or 0.25) end
    if plain then return end
    r.sel = Tex(r, "BACKGROUND", "fade_h", 1)
    r.sel:SetAllPoints(); Paint(r.sel, GOLD); r.sel:SetAlpha(0)
    r.bar = Tex(r, "ARTWORK")
    r.bar:SetPoint("TOPLEFT"); r.bar:SetPoint("BOTTOMLEFT"); r.bar:SetWidth(2)
    Paint(r.bar, YELLOW); r.bar:SetAlpha(0)
    function r:SetSelected(on)
        Fade(self.sel, on and 0.34 or 0, 0.15)
        Fade(self.bar, on and 1 or 0, 0.15)
    end
end

-- A thin scroll mark on the right edge of a list. Place(first, visible,
-- total) sizes and moves it, or hides it when everything fits.
local function ScrollMark(list)
    local track = Tex(list, "BACKGROUND")
    Paint(track, BRONZE, 0.22)
    track:SetPoint("TOPRIGHT"); track:SetPoint("BOTTOMRIGHT"); track:SetWidth(3)
    local thumb = Tex(list, "ARTWORK")
    Paint(thumb, GOLD, 0.95)
    thumb:SetWidth(3)
    local m = { track = track, thumb = thumb }
    function m:Place(first, visible, total)
        if total <= visible then thumb:Hide(); track:Hide() return end
        local h = list:GetHeight()
        local th = math.max(20, h * visible / total)
        thumb:SetHeight(th)
        thumb:ClearAllPoints()
        thumb:SetPoint("TOPRIGHT", list, "TOPRIGHT", 0, -(h - th) * first / (total - visible))
        thumb:Show(); track:Show()
    end
    return m
end

-- The shell of a window: soft shadow, dark panel, bronze edge with gold
-- corners, and the title bar, which is returned (the caller makes it the
-- drag handle and fills it). The window fades in when shown, and the gold
-- rule under its title opens from the centre.
local function Shell(f)
    -- Shadow, sliced in nine: 28 px corners of a 64 px texture, 20 px outside.
    local c = 28 / 64
    local function Part(l, r, t, b)
        local p = Tex(f, "BACKGROUND", "shadow", -8)
        p:SetTexCoord(l, r, t, b)
        return p
    end
    local tl = Part(0, c, 0, c);          tl:SetSize(28, 28); tl:SetPoint("TOPLEFT", -20, 20)
    local tr = Part(1 - c, 1, 0, c);      tr:SetSize(28, 28); tr:SetPoint("TOPRIGHT", 20, 20)
    local bl = Part(0, c, 1 - c, 1);      bl:SetSize(28, 28); bl:SetPoint("BOTTOMLEFT", -20, -20)
    local br = Part(1 - c, 1, 1 - c, 1);  br:SetSize(28, 28); br:SetPoint("BOTTOMRIGHT", 20, -20)
    local top = Part(c, 1 - c, 0, c);     top:SetPoint("TOPLEFT", tl, "TOPRIGHT", 0, 0); top:SetPoint("BOTTOMRIGHT", tr, "BOTTOMLEFT", 0, 0)
    local bot = Part(c, 1 - c, 1 - c, 1); bot:SetPoint("TOPLEFT", bl, "TOPRIGHT", 0, 0); bot:SetPoint("BOTTOMRIGHT", br, "BOTTOMLEFT", 0, 0)
    local lef = Part(0, c, c, 1 - c);     lef:SetPoint("TOPLEFT", tl, "BOTTOMLEFT", 0, 0); lef:SetPoint("BOTTOMRIGHT", bl, "TOPRIGHT", 0, 0)
    local rig = Part(1 - c, 1, c, 1 - c); rig:SetPoint("TOPLEFT", tr, "BOTTOMLEFT", 0, 0); rig:SetPoint("BOTTOMRIGHT", br, "TOPRIGHT", 0, 0)

    local bg = Tex(f, "BACKGROUND", nil, -6)
    bg:SetAllPoints()
    bg:SetVertexColor(0.058, 0.048, 0.037, 0.97)
    local warm = Tex(f, "BACKGROUND", "fade_v", -5)              -- warm light under the title bar
    warm:SetPoint("TOPLEFT", 1, -BAR_H); warm:SetPoint("TOPRIGHT", -1, -BAR_H)
