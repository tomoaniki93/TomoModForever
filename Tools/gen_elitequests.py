"""Build Modules/QOL/Forever/EliteQuestData.lua from Tools/elite_quests.txt.

Usage: python gen_elitequests.py <elite_quests.txt> <out.lua> [elite_quest_pins.txt]
Input: "[zoneKey|uiMapID or -|English name|French name]" headers, then
"ID|name|level|required level|side" lines (side A / H / B).
"""
import sys

src, out = sys.argv[1], sys.argv[2]
pins = {}
if len(sys.argv) > 3:
    for raw in open(sys.argv[3], encoding="utf-8"):
        f = raw.rstrip("\n").split("|")
        if len(f) == 9:
            pins[int(f[0])] = f[1:]
zones, cur = [], None
for raw in open(src, encoding="utf-8"):
    line = raw.strip()
    if not line or line.startswith("#"):
        continue
    if line.startswith("["):
        key, mid, en, fr = line.strip("[]").split("|")
        cur = {"key": key, "id": None if mid == "-" else int(mid), "en": en, "fr": fr, "q": []}
        zones.append(cur)
        continue
    qid, name, level, req, side = line.split("|")
    assert side in ("A", "H", "B"), line
    cur["q"].append((int(qid), name, int(level), int(req), side))

def lua(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

lines = [
    "-- =====================================================================",
    "-- Modules/QOL/Forever/EliteQuestData.lua -- elite quests of the world",
    "--",
    "-- The quests foreverchanges.pro marks Elite on its zone pages (Nov 2026),",
    "-- dungeons and raids left out (the codex lists dungeon quests apart).",
    "-- Generated by Tools/gen_elitequests.py from Tools/elite_quests.txt.",
    "--   zones = { { key, mapID (Classic uiMapID or nil), en, fr,",
    "--               quests = { { questID, name (enUS), level, minLevel, side,",
    "--                            giver, mapID, x, y, ender, endMapID, endX, endY }, ... } }, ... }",
    "-- giver: NPC name, or \"item:<name>\" when an item starts the quest. Positions",
    "-- (Classic uiMapID, x / y in %) from each quest's foreverchanges.pro page,",
    "-- parsed by Tools/parse_quest_pins.py; nil when the page gives none.",
    "-- side: \"A\", \"H\" or \"B\" (both).",
    "-- =====================================================================",
    "",
    "TomoMod_EliteQuestData = {",
]
total = 0
for z in zones:
    lines.append("    {{ key = \"{}\", id = {}, en = {}, fr = {}, quests = {{".format(
        z["key"], z["id"] if z["id"] else "nil", lua(z["en"]), lua(z["fr"])))
    for qid, name, level, req, side in sorted(z["q"], key=lambda q: (q[2], q[1])):
        total += 1
        p = pins.get(qid, ["-"] * 8)
        def v(x, num=False):
            if x == "-" or x == "": return "nil"
            return x if num else lua(x)
        lines.append("        {{ {}, {}, {}, {}, \"{}\", {}, {}, {}, {}, {}, {}, {}, {} }},".format(
            qid, lua(name), level, req, side,
            v(p[3]), v(p[0], True), v(p[1], True), v(p[2], True),
            v(p[7]), v(p[4], True), v(p[5], True), v(p[6], True)))
    lines.append("    } },")
lines.append("}")
open(out, "w", encoding="utf-8").write("\n".join(lines) + "\n")
print(len(zones), "zones,", total, "elite quests")
