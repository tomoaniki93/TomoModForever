"""Build Modules/QOL/Forever/DungeonQuestData.lua from a pipe-separated list.

Usage: python gen_dungeonquests.py <quests.txt> <out.lua>
Input: "[codexKey]" headers, then "ID|name|level|side|giver|prereq" lines
(side A / H / B, "-" for unknown, giver "item:Name" when an item starts it).
"""
import sys

src, out = sys.argv[1], sys.argv[2]
groups, order, key = {}, [], None
for raw in open(src, encoding="utf-8"):
    line = raw.strip()
    if not line or line.startswith("#"):
        continue
    if line.startswith("["):
        key = line.strip("[]")
        order.append(key)
        groups[key] = []
        continue
    qid, name, level, side, giver, prereq = line.split("|")
    assert side in ("A", "H", "B"), line
    groups[key].append((int(qid), name, None if level == "-" else int(level), side,
                        None if giver == "-" else giver, None if prereq == "-" else int(prereq)))

def lua(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

lines = [
    "-- =====================================================================",
    "-- Modules/QOL/Forever/DungeonQuestData.lua -- quests of each dungeon",
    "--",
    "-- Compiled from the public Forever databases foreverchanges.pro and",
    "-- wowforevertalents.com (Nov 2026), one list per codex dungeon (wings",
    "-- have their own list). Generated by Tools/gen_dungeonquests.py.",
    "--   [codexKey] = { { questID, name (enUS), level, side, giver, prereq }, ... }",
    "-- side: \"A\", \"H\" or \"B\" (both). giver: NPC name, or \"item:<name>\" when an",
    "-- item starts the quest; nil if unknown. prereq: quest ID before it, or nil.",
    "-- The codex shows the client's own quest title when it has it.",
    "-- =====================================================================",
    "",
    "TomoMod_DungeonQuestData = {",
]
total = 0
for k in order:
    lines.append(f"    {k} = {{")
    for qid, name, level, side, giver, prereq in sorted(groups[k], key=lambda q: (q[2] or 0, q[1])):
        total += 1
        lines.append("        {{ {}, {}, {}, \"{}\", {}, {} }},".format(
            qid, lua(name), level if level is not None else "nil", side,
            lua(giver) if giver else "nil", prereq if prereq else "nil"))
    lines.append("    },")
lines.append("}")
open(out, "w", encoding="utf-8").write("\n".join(lines) + "\n")
print(len(order), "dungeons,", total, "quests")
