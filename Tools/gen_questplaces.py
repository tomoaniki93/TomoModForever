"""Build Modules/QOL/Forever/DungeonQuestPlaces.lua.

Usage: python gen_questplaces.py <dungeon_quest_pages.jsonl> <out.lua> <list.txt> [<list.txt> ...]
Lists: Tools/dungeon_quests.txt and Tools/elite_quests.txt (ID|name|level|...).
The .jsonl comes from parse_quest_pages.py (one quest page per line).
"""
import json, sys

pages_file, out, list_files = sys.argv[1], sys.argv[2], sys.argv[3:]
recs = {r["id"]: r for r in (json.loads(l) for l in open(pages_file, encoding="utf-8"))}

titles, levels = {}, {}
for raw in (l for f in list_files for l in open(f, encoding="utf-8")):
    line = raw.strip()
    if line and not line.startswith(("#", "[")):
        f = line.split("|")
        titles[int(f[0])] = f[1]
        levels[int(f[0])] = None if f[2] == "-" else int(f[2])
for r in recs.values():
    for step in r.get("chain", []):
        for q in step:
            titles.setdefault(q["id"], q["title"])
            if q.get("level"): levels.setdefault(q["id"], q["level"])

def lua(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'

def num(v):
    if v is None: return "nil"
    return str(int(v)) if float(v).is_integer() else f"{v:g}"

def place(p):
    if not p: return None
    parts = [num(p.get("map")) if p.get("x") is not None else "nil",
             num(p.get("x")), num(p.get("y")), lua(p["name"]) if p.get("name") else "nil"]
    s = "{ " + ", ".join(parts)
    if p.get("item"): s += ", item = true"
    return s + " }"

lines = [
    "-- =====================================================================",
    "-- Modules/QOL/Forever/DungeonQuestPlaces.lua -- where dungeon quests start",
    "--",
    "-- From each quest's page on foreverchanges.pro (Nov 2026): the dungeon",
    "-- quests of DungeonQuestData.lua, the elite quests of EliteQuestData.lua",
    "-- and every quest of their chains.",
    "-- Generated by Tools/gen_questplaces.py from Tools/dungeon_quest_pages.jsonl",
    "-- (Tools/parse_quest_pages.py).",
    "--   [questID] = { t = title (enUS), l = level,",
    "--                 s = { mapID, x, y, giver[, item = true] },   -- start",
    "--                 e = { mapID, x, y, NPC },                    -- turn-in",
    "--                 c = { { questID, ... }, ... } }              -- chain steps before it",
    "-- mapID / x / y are nil when the page gives no position; item = true when",
    "-- an item starts the quest (giver is then the item's name).",
    "-- =====================================================================",
    "",
    "TomoMod_DungeonQuestPlaces = {",
]
for qid in sorted(recs):
    r = recs[qid]
    fields = []
    if qid in titles: fields.append("t = " + lua(titles[qid]))
    if levels.get(qid): fields.append("l = " + str(levels[qid]))
    s, e = place(r.get("start")), place(r.get("end"))
    if s: fields.append("s = " + s)
    if e: fields.append("e = " + e)
    if r.get("chain"):
        fields.append("c = { " + ", ".join("{ " + ", ".join(str(q["id"]) for q in step) + " }" for step in r["chain"]) + " }")
    lines.append(f"    [{qid}] = {{ " + ", ".join(fields) + " },")
lines.append("}")
open(out, "w", encoding="utf-8").write("\n".join(lines) + "\n")
print(len(recs), "quests")
