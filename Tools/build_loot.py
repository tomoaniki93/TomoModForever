#!/usr/bin/env python3
"""Build TomoModForever's Modules/QOL/Forever/DungeonLootData.lua from
ForeverLoot's Data.lua (dungeon loot only, used with the author's permission).

usage: build_loot.py <ForeverLoot/Data.lua> <out.lua>
"""
import re
import sys

src, out = sys.argv[1], sys.argv[2]
s = open(src, encoding="utf-8").read()
date = re.search(r'ns\.DATA_DATE = "([^"]+)"', s).group(1)
dungeons = s[s.index("ns.Dungeons"):s.index("ns.Raids")]
items_part = s[s.index("ns.Items"):]

# ForeverLoot key (+ wing) -> TomoMod codex key
SIMPLE = {
    "HOT": "hot", "ROL": "rol", "EXC": "exc", "DAL": "dal", "DROWN": "drowned",
    "KROL": "kroldok", "ALCAZ": "alcaz", "BMH": "blackmaw", "SHAPER": "shaper",
    "RFC": "rfc", "DM": "vc", "WC": "wc", "SFK": "sfk", "BFD": "bfd",
    "STOCKS": "stocks", "GNOMER": "gnomer", "RFK": "rfk", "RFD": "rfd",
    "ULDA": "ulda", "MARA": "mara", "ZF": "zf", "ST": "st", "BRD": "brd",
    "SCHOLO": "scholo",
}
WINGS = {
    "SM": {"Graveyard": "smgy", "Library": "smlib", "Armory": "smarm", "Cathedral": "smcath"},
    "DIRE": {"East": "dme", "West": "dmw", "North": "dmn"},
    "STRAT": {"Main Gate": "stratlive", "Service Entrance": "stratud"},
    "BRS": {"Lower Spire": "lbrs", "Upper Spire": "ubrs"},
}
TAGS = {
    "Any mob in the dungeon": "trash", "Event boss": "event", "Rare spawn": "rare",
    "Scourge Invasion event": "scourge", "Summoned": "summoned",
    "Tribute chest": "tribute", "Datamined on Wowhead": "datamined",
}

def lua_str(t):
    return '"' + t.replace("\\", "\\\\").replace('"', '\\"') + '"'

result = {}      # codex key -> list of boss dicts
used = set()
for m in re.finditer(r'key = "(\w+)", name = "([^"]+)"(.*?)\n\t\},\n', dungeons, re.S):
    key, _name, body = m.groups()
    for b in re.finditer(r'\{ name = "([^"]+)"([^\n]*?)loot = \{([^}]*)\}', body):
        bname, attrs, loot = b.groups()
        ids = [int(x) for x in re.findall(r"\d+", loot)]
        tag = re.search(r'tag = "([^"]+)"', attrs)
        wing = re.search(r'wing = "([^"]+)"', attrs)
        boss = {
            "name": bname,
            "tag": TAGS.get(tag.group(1)) if tag else None,
            "trash": "trash = true" in attrs,
            "unconfirmed": "unconfirmed = true" in attrs,
            "loot": ids,
        }
        if key in WINGS:
            wing_name = wing.group(1) if wing else None
            if wing_name in WINGS[key]:
                targets = [WINGS[key][wing_name]]
            else:  # "Event bosses", trash, no wing: every wing of the instance
                targets = list(WINGS[key].values())
        elif key in SIMPLE:
            targets = [SIMPLE[key]]
        else:
            continue
        for t in targets:
            result.setdefault(t, []).append(boss)
        used.update(ids)
    # dungeons with no boss yet still get an (empty) entry
    for t in ([SIMPLE[key]] if key in SIMPLE else list(WINGS.get(key, {}).values())):
        result.setdefault(t, [])

# Offline fallback for the items used: quality, icon, English name and type
items = {}
for m in re.finditer(r'^\t\[(\d+)\] = \{ "((?:[^"\\]|\\.)*)", (\d+), "((?:[^"\\]|\\.)*)", \d+, "[^"]*", "((?:[^"\\]|\\.)*)"', items_part, re.M):
    iid = int(m.group(1))
    if iid in used:
        icon = m.group(5).replace("\\\\", "\\")
        icon = re.sub(r"(?i)^interface\\icons\\", "", icon)
        items[iid] = (int(m.group(3)), icon, m.group(2), m.group(4))

L = []
L.append("-- =====================================================================")
L.append("-- Modules/QOL/Forever/DungeonLootData.lua -- dungeon loot for the codex")
L.append("--")
L.append("-- Loot data from ForeverLoot by Ethan Elliott, used with the author's")
L.append("-- permission. ForeverLoot builds it from Wowhead, wowtbc.gg, Mobalytics")
L.append("-- and cMaNGOS. Thank you!")
L.append("--   https://www.curseforge.com/wow/addons/forever-loot")
L.append(f"--   ForeverLoot 1.12.1, data of {date}")
L.append("--")
L.append("-- Generated by Tools/build_loot.py: dungeon bosses only (no raids, sets,")
L.append("-- quests or professions), mapped onto the codex keys and wings. Do not")
L.append("-- edit by hand; rebuild it from a newer ForeverLoot Data.lua instead.")
L.append("--")
L.append("-- loot[codexKey] = { { n = boss name (English), t = tag, trash = true,")
L.append("--                      u = true (unconfirmed), i = { itemID, ... } }, ... }")
L.append("-- items[itemID]  = { quality, icon (Interface\\Icons\\...), name, type }:")
L.append("--   shown only until the client knows the item (names in English).")
L.append("-- =====================================================================")
L.append("")
L.append("TomoMod_DungeonLootData = {")
L.append(f'    source = "ForeverLoot 1.12.1 (Ethan Elliott)",')
L.append(f'    date = "{date}",')
L.append("    loot = {")
for key in sorted(result):
    L.append(f"        {key} = {{")
    for b in result[key]:
        parts = [f"n = {lua_str(b['name'])}"]
        if b["tag"]:
            parts.append(f'"t = "{b["tag"]}"'[1:] if False else f't = "{b["tag"]}"')
        if b["trash"]:
            parts.append("trash = true")
        if b["unconfirmed"]:
            parts.append("u = true")
        parts.append("i = { " + ", ".join(str(i) for i in b["loot"]) + " }")
        L.append("            { " + ", ".join(parts) + " },")
    L.append("        },")
L.append("    },")
L.append("    items = {")
for iid in sorted(items):
    q, icon, name, typ = items[iid]
    L.append(f"        [{iid}] = {{ {q}, {lua_str(icon)}, {lua_str(name)}, {lua_str(typ)} }},")
L.append("    },")
L.append("}")
open(out, "w", encoding="utf-8").write("\n".join(L) + "\n")
print(f"{len(result)} dungeons, {sum(len(v) for v in result.values())} boss entries, "
      f"{len(used)} items used, {len(items)} with fallback info")
missing = set().union(*[set(SIMPLE.values())] + [set(w.values()) for w in WINGS.values()]) - set(result)
print("codex keys without data:", sorted(missing))
