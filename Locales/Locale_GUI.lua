-- Shared lookup: frFR -> fr ; other locales -> table[en] ; else English.
local LOCALE = GetLocale and GetLocale() or "enUS"
local TABLE = TomoMod_GUIL[LOCALE]
function TomoMod_GUIT(fr, en)
    if LOCALE == "frFR" then return fr end
    if en == nil then return fr end
    if TABLE then return TABLE[en] or en end
    return en
end
